"""Build nine-slice pixel frames using each page's existing illustration palette."""
from pathlib import Path
from urllib.parse import quote
import re

site = Path(__file__).resolve().parents[1]
styles = site / 'design_system/styles'
palette = (styles / 'illustration-palette.css').read_text(encoding='utf-8')
rules = ['/* Generated by scripts/build-pixel-frames-v16.py. Native SVG border slices keep every corner crisp at any card size. */']
for selector, color in re.findall(r'(body\.signal-atlas[^\{]+)\{--v-accent:(#[0-9a-f]{6})', palette):
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32" viewBox="0 0 32 32"><path d="M8 1H24V4H28V8H31V24H28V28H24V31H8V28H4V24H1V8H4V4H8Z" fill="none" stroke="{color}" stroke-opacity=".58" stroke-width="2" shape-rendering="crispEdges"/></svg>'
    rules.append(f'{selector}{{--pixel-frame:url("data:image/svg+xml,{quote(svg)}");}}')

# Only existing bounded cards/callouts: reading sections and interaction canvases remain open.
cards = '''sust-ledger-card contrib-rcard eng-evidence-card members-card eng-overview-card hp-eng-card
design-card ent-ballot-card ent-wcard members-postcard__card parts-or-card hp-cp__card
saf-layers__card saf-glance__card saf-award__card learn-diff__card members-memory__card
eng-hyp-chain__card eng-metric-compare__card saf-equip__card saf-q3__card saf-compare__card
saf-fnfp__card sust-sdgmap__card design-callout ent-callout saf-callout audit-boundary
audit-feature audit-download audit-source-note audit-nutshell audit-equation exp-note hw-v2-note
audit-scope notice sust-note model-callout model-metric model-method re-highlight re-callout
learn-card learn-activity lm-check lm-concept nb-record member-card parts-card eng-glance__card
lm-qc__card lm-quiz__card parts-feature-detail'''.split()
selector = 'body.signal-atlas:not(.page-home) :is(' + ','.join('.' + c for c in cards) + '):not(.section-block)'
rules.append(selector + '''{
 box-sizing:border-box;border:8px solid transparent!important;
 border-image:var(--pixel-frame) 8 stretch!important;
 border-radius:0!important;clip-path:var(--pixel-corner);
 box-shadow:none!important;min-width:0;
}
''')
rules.append(selector + ':focus-visible{outline-offset:-5px!important}\n')
# Headings retain alignment and their existing watercolor wash; the clipped edge is intentional.
rules.append('body.signal-atlas .learn-node{box-shadow:none!important}\n')
rules.append('body.signal-atlas .page-article>.section-block.audit-feature{clip-path:none!important}\n')
rules.append('body.signal-atlas :is(.members-card,.members-postcard__card){transform:none!important}\n')
(styles / 'pixel-frames-v16.css').write_text('\n'.join(rules), encoding='utf-8')
print(f'Wrote pixel frames for {len(cards)} existing card/callout types.')
